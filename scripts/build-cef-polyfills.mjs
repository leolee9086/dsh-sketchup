import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
// Produce browser-safe source as a string; the Host does not import core-js.
const result = await build({
  absWorkingDir: root,
  entryPoints: ['scripts/cef-polyfills-entry.js'],
  bundle: true, platform: 'browser', format: 'iife', target: ['chrome80'],
  minify: true, write: false, legalComments: 'inline', charset: 'ascii',
});
const source = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
await mkdir(path.join(root, 'src/generated'), { recursive: true });
await writeFile(path.join(root, 'src/generated/cef-polyfills.ts'),
  '// Generated by scripts/build-cef-polyfills.mjs. Do not edit.\n'
  + 'export const cefPolyfillSource: string = ' + JSON.stringify(source) + ';\n');
console.log(`CEF standard polyfill bundle: ${Buffer.byteLength(source)} bytes`);
